// Generate realistic 90-day historical candles leading up to current price
function generateHistoricalCandles(basePrice: number, volatility: number, trend: 'up' | 'down' | 'sideways'): HistoricalCandle[] {
  const candles: HistoricalCandle[] = [];
  const days = 90;
  let price = basePrice * (trend === 'up' ? 0.82 : trend === 'down' ? 1.18 : 0.96);
  const now = new Date();

  for (let i = days; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = d.toISOString().split('T')[0];
    
    // Daily return with small drift
    const drift = trend === 'up' ? 0.0022 : trend === 'down' ? -0.0018 : 0.0003;
    const randomChange = (Math.random() - 0.48) * volatility + drift;
    const open = price;
    const close = Math.round((open * (1 + randomChange)) * 100) / 100;
    const high = Math.round((Math.max(open, close) * (1 + Math.random() * (volatility * 0.7))) * 100) / 100;
    const low = Math.round((Math.min(open, close) * (1 - Math.random() * (volatility * 0.7))) * 100) / 100;
    const volume = Math.round(1200000 + Math.random() * 2500000);

    candles.push({
      date: dateStr,
      open,
      high,
      low,
      close,
      volume,
    });

    price = close;
  }

  // Adjust final candle to match exact basePrice
  const last = candles[candles.length - 1];
  last.close = basePrice;
  last.high = Math.max(last.high, basePrice);
  last.low = Math.min(last.low, basePrice);

  return candles;
}

