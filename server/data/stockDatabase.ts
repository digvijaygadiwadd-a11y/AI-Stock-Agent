// Generate dynamic record for ANY symbol (e.g. unknown symbols, newly searched tickers)
function generateDynamicCustomRecord(ticker: string): StockDataRecord {
  const normTicker = ticker.trim().toUpperCase().replace(/[^A-Z0-9.-]/g, '').slice(0, 12);
  
  // Deterministic seed from ticker string
  let hash = 0;
  for (let i = 0; i < normTicker.length; i++) {
    hash = (hash << 5) - hash + normTicker.charCodeAt(i);
    hash |= 0;
  }
  const posHash = Math.abs(hash);

  const isIndian = normTicker.length > 4 || ['TATAPOWER', 'HAL', 'BHEL', 'IRCTC', 'PAYTM', 'SWIGGY', 'ZOMATO', 'ITC', 'SBI', 'PNB', 'SAIL', 'GAIL', 'IOC'].includes(normTicker);
  const currency = isIndian ? 'INR (₹)' : 'USD ($)';
  const exchange = isIndian ? 'NSE' : 'NASDAQ';
  const country = isIndian ? 'India' : 'United States';
  const market = isIndian ? 'Emerging Markets' : 'Global Markets';

  const basePrice = isIndian
    ? Math.round(50 + (posHash % 4500) + (posHash % 100) * 0.5)
    : Math.round(15 + (posHash % 450) + (posHash % 100) * 0.25);

  const sectorList = [
    'Technology & AI',
    'Financial Services',
    'Healthcare & Pharma',
    'Consumer Discretionary',
    'Industrials & Defense',
    'Energy & Renewables',
    'Materials & Mining',
  ];
  const sector = sectorList[posHash % sectorList.length];

  const preset: KnownStockPreset = {
    name: `${normTicker} Corporation`,
    exchange: exchange as any,
    country,
    market,
    currency,
    sector,
    industry: `${sector} Core Operations`,
    basePrice,
    volatility: 0.016 + (posHash % 10) * 0.001,
    trend: (posHash % 3 === 0 ? 'up' : posHash % 3 === 1 ? 'sideways' : 'up'),
    marketCap: isIndian ? Math.round(1500 + (posHash % 25000)) : Math.round(50 + (posHash % 950)),
    pe: Math.round(15 + (posHash % 40)),
    pb: Math.round(1.8 + (posHash % 12) * 0.5),
    roe: Math.round(12 + (posHash % 22)),
    netMargin: Math.round(8 + (posHash % 20)),
    debtToEquity: Math.round(((posHash % 80) / 100) * 100) / 100,
    revGrowth: Math.round(8 + (posHash % 25)),
    newsHeadline: `${normTicker} reports strong operational momentum in quarterly business performance review`,
    newsSource: isIndian ? 'Financial Daily' : 'MarketWatch',
    thesis: `Solid balance sheet structure and growing cash generation provide favorable risk/reward in ${sector}.`,
  };

  return generateStockRecordFromPreset(normTicker, preset);
}

// Master accessor: Retrieves from cache/DB or seamlessly constructs record
export function getOrCreateStockRecord(ticker: string): StockDataRecord {
  const normTicker = ticker.trim().toUpperCase().replace(/[^A-Z0-9.-]/g, '');
  if (!normTicker) {
    return STOCK_DATABASE['RELIANCE'];
  }

  // 1. Direct hit in pre-loaded database
  if (STOCK_DATABASE[normTicker]) {
    return STOCK_DATABASE[normTicker];
  }

  // 2. Preset hit in metadata registry
  if (KNOWN_STOCKS_METADATA[normTicker]) {
    const record = generateStockRecordFromPreset(normTicker, KNOWN_STOCKS_METADATA[normTicker]);
    STOCK_DATABASE[normTicker] = record;
    return record;
  }

  // 3. Dynamic synthesis for ANY custom ticker entered by user
  const dynamicRecord = generateDynamicCustomRecord(normTicker);
  STOCK_DATABASE[normTicker] = dynamicRecord;
  return dynamicRecord;
}

